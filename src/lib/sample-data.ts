export const SAMPLE_DAILY_ANALYTICS: DailyAnalyticsSnapshot[] = Array.from({ length: 30 }).map((_, i) => {
  const dayOffset = 29 - i;
  const d = new Date(Date.now() - dayOffset * 24 * 60 * 60 * 1000);
  const dateStr = d.toISOString().split('T')[0];

  // Realistic seasonal curve + organic growth
  const baseGrowth = i * 1400;
  const ytViews = Math.floor(45000 + baseGrowth * 0.8 + Math.sin(i * 0.5) * 8000 + (i === 28 ? 35000 : 0));
  const igViews = Math.floor(28000 + baseGrowth * 0.5 + Math.cos(i * 0.6) * 5000);
  const ttViews = Math.floor(75000 + baseGrowth * 1.4 + Math.sin(i * 0.4) * 15000 + (i === 27 ? 80000 : 0));

  const ytSubs = Math.floor(118000 + i * 350);
  const igFollowers = Math.floor(76000 + i * 270);
  const ttFollowers = Math.floor(215000 + i * 1020);

  const netNew = Math.floor(1200 + Math.sin(i * 0.7) * 400 + (i > 25 ? 900 : 0));

  return {
    date: dateStr,
    combinedViews: ytViews + igViews + ttViews,
    youtubeViews: ytViews,
    instagramViews: igViews,
    tiktokViews: ttViews,
    totalFollowers: ytSubs + igFollowers + ttFollowers,
    youtubeSubscribers: ytSubs,
    instagramFollowers: igFollowers,
    tiktokFollowers: ttFollowers,
    netNewFollowers: netNew,
  };
});

